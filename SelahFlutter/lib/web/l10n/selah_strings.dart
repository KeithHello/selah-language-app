class SelahStrings {
  SelahStrings._(this.locale, Map<String, String> overrides)
    : values = Map.unmodifiable({..._baseStrings, ...overrides});

  final String locale;
  final Map<String, String> values;

  static SelahStrings of(String? locale) {
    final normalized = normalizeUiLocale(locale);
    return switch (normalized) {
      'zh-Hans' => SelahStrings._(normalized, selahZhHansOverrides),
      'ja' => SelahStrings._(normalized, selahJaOverrides),
      _ => SelahStrings._(defaultUiLocale, selahZhHantOverrides),
    };
  }

  Set<String> get keys => values.keys.toSet();

  String text(String key) => values[key] ?? _baseStrings[key] ?? key;

  String message(String key, [Map<String, String> args = const {}]) {
    var value = text(key);
    for (final entry in args.entries) {
      value = value.replaceAll('{${entry.key}}', entry.value);
    }
    return value;
  }

  String tabToday() => text('tab.today');
  String tabListen() => text('tab.listen');
  String tabPractice() => text('tab.practice');
  String tabNotes() => text('tab.notes');
  String tabSettings() => text('tab.settings');
  String languageTitle() => text('settings.language.section');
  String nativeLanguageLabel() => text('settings.language.native');
  String learningLanguageValue() => text('language.en');

  String todayInputHint(String nativeLanguage) => text(
    nativeLanguage == 'ja' ? 'today.inputHint.ja' : 'today.inputHint.zh',
  );

  String todayGreetingTitle() => text('today.greeting.title');

  String todayGreetingSubtitle(String nativeLanguage) => text(
    nativeLanguage == 'ja'
        ? 'today.greeting.subtitle.ja'
        : 'today.greeting.subtitle.zh',
  );

  String recordLabel({required bool recording, required int seconds}) =>
      recording
      ? '${text('today.stop')} ${_formatSeconds(seconds)}'
      : text('today.record');

  String submitLabel({required bool busy, required bool long}) {
    if (busy) return text('today.preparing');
    return text(long ? 'today.organizeLong' : 'today.generate');
  }

  String generatedCount(int count) =>
      message('today.generatedCount', {'count': '$count'});

  String generatedRemaining(int count) =>
      message('today.generatedRemaining', {'count': '$count'});

  String _formatSeconds(int seconds) =>
      '${(seconds ~/ 60).toString().padLeft(2, '0')}:${(seconds % 60).toString().padLeft(2, '0')}';

  String languageLabel(String language) => switch (language) {
    'zh-Hant' => text('language.zhHant'),
    'zh-Hans' => text('language.zhHans'),
    'ja' => text('language.ja'),
    'zh' => text('language.zh'),
    'en' => text('language.en'),
    _ => language,
  };

  String nativeHint(String nativeLanguage) => text(
    nativeLanguage == 'ja'
        ? 'settings.language.nativeHint.ja'
        : 'settings.language.nativeHint.zh',
  );

  /// The loop player describes the role as a language, not as a script
  /// choice.  Both Chinese options therefore read as 中文 there.
  String nativeLanguageValue(String nativeLanguage) =>
      text(nativeLanguage == 'ja' ? 'language.ja' : 'language.zh');

  String categoryLabel(String category) => text('category.$category');

  String voiceLabel(String voice) => text('voice.$voice');

  String reviewLabel(String state) => text('review.$state');

  String vocabularyLabel(String state) => text('vocab.$state');

  String growthLabel(String stage) => text('growth.$stage');

  String pageLabel(String label) => locale == 'ja'
      ? '$labelページ'
      : locale == 'zh-Hant'
      ? '$label頁'
      : '$label页';

  String sessionCount(int count) => locale == 'ja'
      ? '$count回の練習'
      : locale == 'zh-Hant'
      ? '$count 次練習'
      : '$count 次练习';

  String segmentLabel(int index) => locale == 'ja'
      ? '第$indexセグメント'
      : locale == 'zh-Hant'
      ? '第 $index 段'
      : '第 $index 段';

  String confirmGenerateLabel({required bool busy}) => busy
      ? text('today.preparing')
      : locale == 'ja'
      ? '確認して生成'
      : locale == 'zh-Hant'
      ? '確認並產生'
      : '确认并生成';

  String memoryTitle(String key) => text('memory.$key.title');

  String memorySubtitle(String key) => text('memory.$key.subtitle');

  String translateLegacy(String value) {
    if (locale == 'zh-Hans') return value;
    final translated = _legacyTranslations[locale]?[value];
    return translated ?? value;
  }
}

