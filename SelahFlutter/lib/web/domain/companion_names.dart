  absurdEasterEgg,
}

class CompanionNameEntry {
  const CompanionNameEntry({
    required this.id,
    required this.concept,
    required this.zhHant,
    required this.zhHans,
    required this.ja,
    required this.category,
    required this.tone,
    required this.isInitialDefault,
  });

  final int id;
  final String concept;
  final String zhHant;
  final String zhHans;
  final String ja;
  final CompanionNameCategory category;
  final String tone;
  final bool isInitialDefault;

  String nameForLanguage(String languageCode) {
    final normalized = normalizeNativeLanguage(languageCode);
    switch (normalized) {
      case 'zh-Hant':
        return zhHant;
      case 'zh-Hans':
        return zhHans;
      case 'ja':
        return ja;
      default:
        return zhHant;
    }
  }
}

