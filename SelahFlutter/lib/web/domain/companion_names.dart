  static List<CompanionNameEntry> get defaultInitialPool =>
      all.where((e) => e.isInitialDefault).toList(growable: false);

  static CompanionNameEntry initialDefaultEntry({Random? random}) {
    final rng = random ?? Random();
    final pool = defaultInitialPool;
    return pool[rng.nextInt(pool.length)];
  }

  static String initialDefaultName(String languageCode, {Random? random}) {
    return initialDefaultEntry(random: random).nameForLanguage(languageCode);
  }

  static CompanionNameEntry randomEntry({
    String? currentName,
    String? languageCode,
    Random? random,
  }) {
    final rng = random ?? Random();
    final currentClean = currentName?.trim();
    final candidates = all.where((e) {
      if (currentClean == null || currentClean.isEmpty) return true;
      if (languageCode != null) {
        return e.nameForLanguage(languageCode) != currentClean;
      }
      return e.zhHant != currentClean &&
          e.zhHans != currentClean &&
          e.ja != currentClean;
    }).toList(growable: false);

    final pool = candidates.isNotEmpty ? candidates : all;
    return pool[rng.nextInt(pool.length)];
  }

  static String randomName(
    String languageCode, {
    String? currentName,
    Random? random,
  }) {
    return randomEntry(
      currentName: currentName,
      languageCode: languageCode,
      random: random,
    ).nameForLanguage(languageCode);
  }
